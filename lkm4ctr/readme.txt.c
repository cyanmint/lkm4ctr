const char lkm4ctr_readme_txt_data[] =
"lkm4ctr diagfs - readme\n"
"========================\n"
"\n"
"This is the \"lkm4ctr\" pseudo-filesystem exposed by the lkm4ctr.ko kernel\n"
"module. Mounting it gives you a read/write diagnostics and control tree\n"
"covering every subsystem linked into lkm4ctr.ko: shadow_hijack (the shared\n"
"hook engine), vendor_kernel and shadow_cgdevices, plus module-wide\n"
"load/unload/hot-reload control.\n"
"\n"
"This file is generated from the canonical diagfs documentation living in\n"
"lkm4ctr/readme.txt.c, and is kept in sync with lkm4ctr_diagfs.c by hand.\n"
"\n"
"Quick start\n"
"-----------\n"
"  # insert the module; vendor_kernel auto-loads at insmod time\n"
"  insmod lkm4ctr.ko\n"
"\n"
"  # mount the filesystem somewhere (any empty directory)\n"
"  mkdir -p /mnt/lkm4ctr\n"
"  mount -t lkm4ctr diag /mnt/lkm4ctr\n"
"\n"
"  # inspect overall state\n"
"  cat /mnt/lkm4ctr/global/status\n"
"  cat /mnt/lkm4ctr/vendor_kernel/status\n"
"  cat /mnt/lkm4ctr/global/log\n"
"\n"
"  # or source the bundled shell helper for a friendlier interface\n"
"  export lkm4ctr_diagfs=/mnt/lkm4ctr\n"
"  . \"$lkm4ctr_diagfs/helper.sh\"\n"
"  lkm4ctr status\n"
"  lkm4ctr help\n"
"\n"
"See \"helper.sh\" below for the full command reference of that wrapper; it\n"
"is entirely optional -- every diagfs file can just as well be read with\n"
"cat/echo directly, which is what the wrapper itself does under the hood.\n"
"\n"
"Every \"control\" file accepts plain-text commands via a single write(2),\n"
"e.g. `echo unload > control`; every \"status\"/\"log\"/listing file is read\n"
"only (open + read, no special ioctl needed) and is regenerated fresh on\n"
"every open(), so repeated `cat`s always show live state.\n"
"\n"
"Root layout\n"
"-----------\n"
"  ./readme.txt                   - this file (0444, read-only).\n"
"  ./helper.sh                    - POSIX-sh helper script (0555,\n"
"                                    read+execute-only); see its own header\n"
"                                    comment or \"Shell helper\" below.\n"
"\n"
"  ./global/control                (0644) - read: command help. write:\n"
"    load                          load every diagfs-managed submodule\n"
"                                   (useful after manual unloads)\n"
"    unload                        graceful whole-module self-unload\n"
"                                   (aliases: 1, remove, graceful)\n"
"    forceunload                   force whole-module self-unload\n"
"                                   (aliases: force, force_unload)\n"
"    force2                        start (or escalate an in-progress\n"
"                                   unload to) the aggressive force2\n"
"                                   sequence, which overrides\n"
"                                   module_refcount() bookkeeping directly\n"
"                                   to push an unload through even when\n"
"                                   references look stuck.\n"
"  ./global/status                 (0444) one of exactly: \"active\",\n"
"                                   \"loading\", \"graceful unloading\",\n"
"                                   \"force unloading\". \"unloaded\" is\n"
"                                   reserved for completeness but is not\n"
"                                   observable once this mount is reachable,\n"
"                                   because the module itself would already\n"
"                                   be gone by then.\n"
"  ./global/log                    (0444) every log line, unfiltered, from\n"
"                                   every subsystem.\n"
"  ./global/resources              (0444) best-effort aggregate of live\n"
"                                   resources already tracked by the hook and\n"
"                                   vendor_kernel registries.\n"
"  ./global/references             (0444) breaks module_refcount() down\n"
"                                   into diagfs mount count + in-flight\n"
"                                   shadow_hook calls + unaccounted \"other\"\n"
"                                   holders, to explain why rmmod is\n"
"                                   refusing to unload lkm4ctr.ko.\n"
"  ./global/hotreload/status       (0444) \"first load\" vs \"hot-reloaded\"\n"
"                                   boot kind, plus in-progress hot-reload\n"
"                                   state.\n"
"  ./global/hotreload/log          (0444) hot-reload subsystem's own log.\n"
"  ./global/hotreload/do-hot-reload\n"
"                                   (0200, write-only) write an absolute\n"
"                                   path to a replacement lkm4ctr.ko to\n"
"                                   trigger a hot reload: validate path ->\n"
"                                   quiesce hooks -> drain refcount ->\n"
"                                   unmount diagfs -> hand off to a\n"
"                                   detached \"rmmod && insmod <path>\n"
"                                   hotreload=1\" shell -> exit. Watch\n"
"                                   ./status and ./log in the same\n"
"                                   directory for progress.\n"
"\n"
"Per-submodule directories\n"
"-------------------------\n"
"Every submodule below (hijack, vendor_kernel, cgroupdevices) has at least:\n"
"  <dir>/control    (0644) read: command help. write: load / unload\n"
"                   (aliases: 1, remove, graceful) / forceunload (aliases:\n"
"                   force, force_unload). force2 is a global-only\n"
"                   escalation and has no per-module meaning here.\n"
"  <dir>/status     (0444) that submodule's own lifecycle state.\n"
"  <dir>/log        (0444) that submodule's own log lines.\n"
"  <dir>/references (0444) that submodule's own contribution to\n"
"                   module_refcount(), broken down the same way\n"
"                   global/references is.\n"
"\n"
"  ./hijack/functions\n"
"    (0444) shadow_hijack is the shared hook engine every other\n"
"    submodule's hooks are installed through, so instead of its own\n"
"    hooks listing it has \"functions\": a live listing of every currently\n"
"    registered hook across all submodules. Ordering rule: since every\n"
"    other submodule depends on this shared engine, hijack's graceful\n"
"    unload is refused (-EBUSY) while any other submodule is still\n"
"    active; forceunload instead gracefully unloads every other active\n"
"    submodule first, waits briefly, force-unloads whatever remains\n"
"    active, then finally tears shadow_hijack itself down.\n"
"\n"
"  ./vendor_kernel/hooks, ./vendor_kernel/namespaces,\n"
"  ./vendor_kernel/msg, ./vendor_kernel/resources\n"
"    (0444 each) vendor_kernel's own installed hooks, full namespace\n"
"    registry dump, current in-memory POSIX message queue/message state,\n"
"    and currently tracked SysV IPC objects. vendor_kernel auto-loads at\n"
"    insmod time, but its control file can still be used to unload or\n"
"    reload it later.\n"
"\n"
"  ./cgroupdevices/hooks\n"
"    (0444) shadow_cgdevices's own installed hooks.\n"
"\n"
"Notes on design\n"
"---------------\n"
"* control vs status is a strict split everywhere: control is the write\n"
"  command surface (and, on read, a short command summary), status is a\n"
"  strict lifecycle-state readout (never a command summary).\n"
"* This is a small, fully in-memory pseudo-filesystem in the same spirit\n"
"  as ramfs/securityfs: the whole tree is built once at mount time; file\n"
"  contents are regenerated fresh on every open(), so state is always\n"
"  live, but the directory/file layout itself never changes after mount.\n"
"* Objects that cannot be enumerated as fixed dentries up front (e.g.\n"
"  currently queued mqueue messages, or live vendor_kernel SysV IPC /\n"
"  namespace objects that may come and go after mount) are exposed as\n"
"  readable listing files (namespaces, msg, resources, functions)\n"
"  rather than one dentry per live object.\n"
"* Everything under ./global and every per-submodule directory keeps\n"
"  working even if some submodules are currently unloaded; only that\n"
"  submodule's own control/status/log/references (and hooks/namespaces/\n"
"  msg/resources where applicable) reflect an \"unloaded\" state until it\n"
"  is loaded again via its control file (or global/control's \"load\").\n"
"\n"
"Shell helper (helper.sh)\n"
"------------------------\n"
"helper.sh is meant to be sourced, not executed:\n"
"  export lkm4ctr_diagfs=/path/to/mountpoint\n"
"  . \"$lkm4ctr_diagfs/helper.sh\"\n"
"\n"
"It then defines an `lkm4ctr` dispatcher function and matching standalone\n"
"functions:\n"
"  lkm4ctr mount                    mount -t lkm4ctr diag \"$lkm4ctr_diagfs\"\n"
"  lkm4ctr umount                   unmount \"$lkm4ctr_diagfs\"\n"
"  lkm4ctr status                   summarise global + every submodule's status\n"
"  lkm4ctr control <target> <cmd>   write <cmd> to <target>/control\n"
"  lkm4ctr load [target]            control <target|global> load\n"
"  lkm4ctr unload [target]          control <target|global> unload\n"
"  lkm4ctr forceunload [target]     control <target|global> forceunload\n"
"  lkm4ctr force2                   control global force2 (aggressive escalation)\n"
"  lkm4ctr logcat [target]          cat <target|global>/log (\"hotreload\" for the hot-reload log)\n"
"  lkm4ctr references [target]      cat <target|global>/references\n"
"  lkm4ctr hot-upgrade <path-to-ko> echo <path> > global/hotreload/do-hot-reload\n"
"  lkm4ctr help                     print this command summary\n"
"\n"
"<target> is one of: global, hijack, vendor_kernel, cgroupdevices.\n"
"$lkm4ctr_diagfs must be exported to the mountpoint before calling any of\n"
"these; every function checks for it and prints a clear error otherwise.\n"
"Run `sh helper.sh` directly (with no arguments) and it just prints this\n"
"same command summary and exits -- it is harmless, but sourcing it is the\n"
"intended usage.\n";

